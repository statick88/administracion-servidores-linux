// Guard: zero brand occurrences (spec S4 of odd/tasks/sitio-web-sin-quarto.md).
// The needle is assembled at runtime so this file itself carries no brand literal.
import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const NEEDLE = ["aba", "com"].join("");
const RE = new RegExp(NEEDLE, "i");

// odd/: verbatim user quotes in the ODD logbook.
// .atl/: auto-generated skill registry mirroring global skill descriptions
// outside this repo (regenerated by `gentle-ai skill-registry refresh`).
const EXCLUDED_DIRS = /^(odd\/|\.atl\/)/;
const TEXT_EXT = /\.(qmd|md|yml|yaml|json|txt|html|css|js|mjs|toml|sh|py|bib|csl|csv|tsv|svg)$/;
const WITH_LICENSE = (f) => TEXT_EXT.test(f) || f === "LICENSE" || f === "CODE_OF_CONDUCT";

function trackedFiles() {
  return execFileSync("git", ["ls-files"], { cwd: ROOT, encoding: "utf8" })
    .split("\n")
    .filter(Boolean)
    .filter((f) => !EXCLUDED_DIRS.test(f))
    .filter((f) => existsSync(join(ROOT, f)));
}

test("tracked file paths never contain the brand", () => {
  const hits = trackedFiles().filter((f) => RE.test(f));
  assert.deepEqual(hits, [], `brand in tracked paths: ${hits.join(", ")}`);
});

test("tracked text sources contain zero brand occurrences", () => {
  const hits = [];
  for (const rel of trackedFiles().filter(WITH_LICENSE)) {
    const text = readFileSync(join(ROOT, rel), "utf8");
    if (RE.test(text)) hits.push(rel);
  }
  assert.deepEqual(hits, [], `brand in tracked sources: ${hits.join(", ")}`);
});

test("built site output contains zero brand occurrences", () => {
  const out = process.env.SITE_OUTPUT || join(ROOT, "_site");
  if (!existsSync(out)) return; // build output checked by CI after the site build (T7)
  const hits = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const p = join(dir, entry);
      if (statSync(p).isDirectory()) walk(p);
      else if (WITH_LICENSE(entry)) {
        if (RE.test(readFileSync(p, "utf8"))) hits.push(p.slice(ROOT.length));
      }
    }
  };
  walk(out);
  assert.deepEqual(hits, [], `brand in build output: ${hits.join(", ")}`);
});
